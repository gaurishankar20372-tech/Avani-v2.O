import { jsPDF } from "jspdf";
import JSZip from "jszip";
import { GeneratedFile } from "../types";

/**
 * Utility to generate PDF, ZIP, and raw files on client-side,
 * and deliver via Download, Web Share API, WhatsApp, or Email.
 */

// Helper to trigger browser download of a Blob
export function triggerBlobDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

// Generate PDF from code or document
export function generatePdfBlob(file: GeneratedFile): Blob {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  const contentWidth = pageWidth - margin * 2;

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 28, "F");

  // Accent Line
  doc.setFillColor(236, 72, 153); // pink-500
  doc.rect(0, 28, pageWidth, 2, "F");

  // Title
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("AVANI AI ASSISTANT", margin, 12);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(244, 114, 182); // pink-400
  doc.text(
    `Document: ${file.title || file.fileName} | Language: ${file.language || "text"}`,
    margin,
    18
  );

  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184); // slate-400
  const dateStr = new Date(file.timestamp || Date.now()).toLocaleString();
  doc.text(`Generated on: ${dateStr}`, margin, 24);

  // File metadata box
  let currentY = 36;
  doc.setFillColor(248, 250, 252); // slate-50
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.roundedRect(margin, currentY, contentWidth, 14, 2, 2, "FD");

  doc.setTextColor(51, 65, 85); // slate-700
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text(`File: ${file.fileName}`, margin + 4, currentY + 6);

  if (file.summary) {
    doc.setFont("helvetica", "italic");
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    const summaryLines = doc.splitTextToSize(`Note: ${file.summary}`, contentWidth - 8);
    doc.text(summaryLines[0] || "", margin + 4, currentY + 11);
  }

  currentY += 20;

  // Code or Document Body
  doc.setFont("courier", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(30, 41, 59);

  const lines = doc.splitTextToSize(file.content || "", contentWidth);
  const lineHeight = 4.2;

  for (let i = 0; i < lines.length; i++) {
    if (currentY + lineHeight > pageHeight - 15) {
      // Add Page
      doc.addPage();
      currentY = 20;

      // Page footer for new page
      doc.setFont("helvetica", "italic");
      doc.setFontSize(7.5);
      doc.setTextColor(148, 163, 184);
      doc.text(
        `Generated by Avani Assistant - Page ${doc.getNumberOfPages()}`,
        margin,
        pageHeight - 8
      );
      doc.setFont("courier", "normal");
      doc.setFontSize(8.5);
      doc.setTextColor(30, 41, 59);
    }
    doc.text(lines[i], margin, currentY);
    currentY += lineHeight;
  }

  // Footer on first page
  doc.setPage(1);
  doc.setFont("helvetica", "italic");
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text(
    `Generated by Avani Voice Assistant | Total Pages: ${doc.getNumberOfPages()}`,
    margin,
    pageHeight - 8
  );

  return doc.output("blob");
}

// Download as PDF
export function downloadPdf(file: GeneratedFile): void {
  const blob = generatePdfBlob(file);
  const baseName = file.fileName.replace(/\.[^/.]+$/, "");
  triggerBlobDownload(blob, `${baseName}.pdf`);
}

// Generate ZIP file containing the code/document and a README.md
export async function generateZipBlob(file: GeneratedFile): Promise<Blob> {
  const zip = new JSZip();

  // Add the primary file
  zip.file(file.fileName, file.content || "");

  // Add a friendly README
  const readmeContent = `# ${file.title || file.fileName}
Generated by **Avani Voice Assistant (अवनी वॉइस असिस्टेंट)**
Date: ${new Date(file.timestamp || Date.now()).toLocaleString()}
Language: ${file.language || "text"}
Type: ${file.fileType || "code"}

## Summary
${file.summary || "Code/Document created upon user request."}

## File Contents
- \`${file.fileName}\`: Primary source code / document

---
*Created with love and a bit of sass by Avani AI.*
`;
  zip.file("README.md", readmeContent);

  return await zip.generateAsync({ type: "blob" });
}

// Download as ZIP
export async function downloadZip(file: GeneratedFile): Promise<void> {
  const blob = await generateZipBlob(file);
  const baseName = file.fileName.replace(/\.[^/.]+$/, "");
  triggerBlobDownload(blob, `${baseName}.zip`);
}

// Download raw code or text file
export function downloadRawFile(file: GeneratedFile): void {
  const blob = new Blob([file.content || ""], { type: "text/plain;charset=utf-8" });
  triggerBlobDownload(blob, file.fileName);
}

// Share using Web Share API or copy link
export async function shareFileOrText(file: GeneratedFile): Promise<boolean> {
  if (navigator.share) {
    try {
      // Try sharing as file if supported
      const rawBlob = new Blob([file.content || ""], { type: "text/plain" });
      const shareFile = new File([rawBlob], file.fileName, { type: "text/plain" });

      if (navigator.canShare && navigator.canShare({ files: [shareFile] })) {
        await navigator.share({
          files: [shareFile],
          title: file.title || file.fileName,
          text: file.summary || `Code from Avani: ${file.fileName}`,
        });
        return true;
      }

      await navigator.share({
        title: file.title || file.fileName,
        text: `${file.title || file.fileName}\n\n${file.content.slice(0, 1000)}...`,
      });
      return true;
    } catch (e: any) {
      if (e.name !== "AbortError") {
        console.warn("Share failed:", e);
      }
    }
  }

  // Fallback to clipboard
  try {
    await navigator.clipboard.writeText(file.content);
    return true;
  } catch (err) {
    console.error("Clipboard copy failed:", err);
    return false;
  }
}

// Send via WhatsApp
export function sendViaWhatsApp(file: GeneratedFile, phone?: string): void {
  const cleanPhone = (phone || "").replace(/[^0-9]/g, "");
  const snippet = file.content.length > 800 ? file.content.slice(0, 800) + "\n...(truncated)" : file.content;
  const message = `*${file.title || file.fileName}* (Generated by Avani)\n\n\`\`\`\n${snippet}\n\`\`\`\n\n_Note: ${file.summary || "Created upon your request."}_`;

  const waUrl = cleanPhone
    ? `https://api.whatsapp.com/send?phone=${cleanPhone}&text=${encodeURIComponent(message)}`
    : `https://api.whatsapp.com/send?text=${encodeURIComponent(message)}`;

  window.open(waUrl, "_blank", "noopener,noreferrer");
}

// Send via Email (mailto)
export function sendViaEmail(file: GeneratedFile, email?: string): void {
  const recipient = email || "";
  const subject = `[Avani Code/Document] ${file.title || file.fileName}`;
  const body = `Hi,\n\nHere is the requested document/code generated by Avani Voice Assistant:\n\n---\nFile: ${file.fileName}\nLanguage: ${file.language}\nSummary: ${file.summary || "None"}\n---\n\n${file.content}\n\nBest regards,\nAvani Assistant`;

  const mailtoUri = `mailto:${recipient}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  window.open(mailtoUri, "_blank", "noopener,noreferrer");
}
